/// `defaultProjectId`: the tenant's first project, created when there is none.
pub async fn default_project_id<E: Exec + Sync>(exec: &E, ctx: &RequestContext) -> R<String> {
    let found = exec
        .first(
            "SELECT p.id::text FROM _basedb.project p
               JOIN _basedb.tenant t ON t.id = p.tenant_id
              WHERE t.ref = $1 AND p.deleted_at IS NULL
              ORDER BY p.position, p.created_at
              LIMIT 1",
            &[&ctx.tenant_id],
        )
        .await?;
    if let Some(r) = found {
        return Ok(r.get(0));
    }
    let rows = exec
        .query_op(
            "INSERT INTO _basedb.project (tenant_id, label, label_key, created_by, updated_by)
             SELECT t.id, 'Projet principal', 'projet principal', $2::text::uuid, $2::text::uuid
               FROM _basedb.tenant t WHERE t.ref = $1
             RETURNING id::text",
            &[&ctx.tenant_id, &ctx.actor.id],
            SqlOp::Insert,
        )
        .await?;
    rows.first().map(|r| r.get(0)).ok_or_else(|| AppError::internal("Cannot read properties of undefined (reading 'id')"))
}

/// `createBase`: one catalog row, one allocated name, one PostgreSQL schema.
pub async fn create_base(pools: &Pools, ctx: &RequestContext, label: &str, description: Option<&Value>, project: Option<&str>) -> R<CreatedBase> {
    let description = normalize_description(description, "description")?;
    let description = &description;
    with_transaction(pools, PoolName::Ddl, ctx, TxOptions::default(), |tx| async move {
        let tenant = tx.first("SELECT id::text, ref FROM _basedb.tenant WHERE ref = $1 AND deleted_at IS NULL", &[&ctx.tenant_id]).await?;
        let Some(tenant) = tenant else {
            return Err(AppError::new("RESOURCE_NOT_FOUND").with("tenant", json!(ctx.tenant_id)));
        };
        let (tenant_id, tenant_ref): (String, String) = (tenant.get(0), tenant.get(1));
        let project_id = match project {
            Some(p) => p.to_string(),
            None => default_project_id(&tx, ctx).await?,
        };
        let target = load_project_target(&tx, ctx, &project_id).await?;
        let mut details = Map::new();
        details.insert("project".into(), json!(project_id));
        require_action(&tx, ctx, Action::ManageSchema, target.clone(), details).await?;
        let project_id = target.map(|t| t.id).unwrap_or_default();

        let clash = tx
            .rows(
                "SELECT id::text FROM _basedb.base WHERE project_id = $1::text::uuid AND label_key = $2 AND deleted_at IS NULL",
                &[&project_id, &label_key(label)],
            )
            .await?;
        if !clash.is_empty() {
            return Err(AppError::new("LABEL_DUPLICATE").with("label", json!(label)));
        }
        let base = tx
            .query_op(
                "INSERT INTO _basedb.base
                   (tenant_id, project_id, label, label_key, description, created_by, updated_by)
                 VALUES ($1::text::uuid, $2::text::uuid, $3, $4, $5, $6::text::uuid, $6::text::uuid) RETURNING id::text",
                &[&tenant_id, &project_id, &label, &label_key(label), description, &ctx.actor.id],
                SqlOp::Insert,
            )
            .await?;
        let base_id: String = base.first().map(|r| r.get(0)).ok_or_else(|| AppError::internal("base not created"))?;
        let mut request = AllocationRequest::new(Candidate::Label(label.to_string()), ObjectKind::Schema, ScopeKind::Instance, SCOPE_INSTANCE);
        request.tenant_id = Some(tenant_ref);
        let name = allocate_name(&tx, ctx, &request).await?;
        tx.query_op(
            "INSERT INTO _basedb.db_schema (base_id, role, name_id, created_by)
             VALUES ($1::text::uuid, 'current', $2::text::uuid, $3::text::uuid) RETURNING id",
            &[&base_id, &name.name_id, &ctx.actor.id],
            SqlOp::Insert,
        )
        .await?;
        ddl(&tx, &sql_create_schema(&name.name)?).await?;
        Ok(CreatedBase { base_id, project_id, description: description.clone(), schema_name: name.name })
    })
    .await
}

/// `updateBase`: label, description and look of a base and of every live environment of it.
pub async fn update_base(pools: &Pools, ctx: &RequestContext, base_id: &str, label: Option<&str>, description: Option<&Value>, look: Option<&LookInput>) -> R<Value> {
    let label = label.map(|l| crate::description::js_trim(l).to_string());
    if let Some(l) = &label {
        if l.is_empty() {
            return Err(AppError::new("LABEL_EMPTY").with("base", json!(base_id)));
        }
        check_label_length(l)?;
    }
    let sets_description = description.is_some();
    let description = if sets_description { normalize_description(description, "description")? } else { None };
    let look = match look {
        Some(l) if l.touches() => Some(normalize_look(l, look_refusal)?),
        _ => None,
    };
    let (label, description, look) = (&label, &description, &look);
    with_transaction(pools, PoolName::Catalog, ctx, TxOptions::default(), |tx| async move {
        let grants = load_grants(&tx, ctx).await?;
        assert_manage_schema(&tx, ctx, &grants, base_id).await?;
        if let Some(l) = label {
            let clash = tx
                .rows(
                    "SELECT b.id::text FROM _basedb.base b
                       JOIN _basedb.base self ON self.id = $2::text::uuid
                      WHERE b.project_id = self.project_id AND b.label_key = $1
                        AND b.deleted_at IS NULL AND b.lineage_id <> self.lineage_id",
                    &[&label_key(l), &base_id],
                )
                .await?;
            if !clash.is_empty() {
                return Err(AppError::new("LABEL_DUPLICATE").with("label", json!(l)));
            }
        }
        let l = look.clone().unwrap_or_default();
        let key = label.as_deref().map(label_key);
        let updated = tx
            .query_op(
                "UPDATE _basedb.base
                    SET label = CASE WHEN $2::boolean THEN $3::text ELSE label END,
                        label_key = CASE WHEN $2::boolean THEN $4::text ELSE label_key END,
                        description = CASE WHEN $5::boolean THEN $6::text ELSE description END,
                        color = CASE WHEN $8::boolean THEN $9::text ELSE color END,
                        icon = CASE WHEN $8::boolean THEN $10::text ELSE icon END,
                        image = CASE WHEN $8::boolean THEN $11::text ELSE image END,
                        catalog_version = catalog_version + 1,
                        updated_at = clock_timestamp(), updated_by = $7::text::uuid
                  WHERE deleted_at IS NULL
                    AND (id = $1::text::uuid OR lineage_id = (SELECT lineage_id FROM _basedb.base WHERE id = $1::text::uuid))
                  RETURNING id::text, label, description, color, icon, image",
                &[&base_id, &label.is_some(), label, &key, &sets_description, description, &ctx.actor.id, &look.is_some(), &l.color, &l.icon, &l.image],
                SqlOp::Update,
            )
            .await?;
        let Some(row) = updated.iter().find(|r| r.get::<_, String>(0) == base_id) else {
            return Err(AppError::new("RESOURCE_NOT_FOUND").with("base", json!(base_id)));
        };
        let out = json!({
            "label": row.get::<_, String>(1),
            "description": row.get::<_, Option<String>>(2),
            "color": row.get::<_, Option<String>>(3),
            "icon": row.get::<_, Option<String>>(4),
            "image": row.get::<_, Option<String>>(5),
        });
        for r in &updated {
            let id: String = r.get(0);
            tx.rows("SELECT pg_notify('basedb_catalog', $1::text)", &[&id]).await?;
        }
        Ok(out)
    })
    .await
}


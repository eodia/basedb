/// `MAX_URL_CHARS`.
pub const MAX_URL_CHARS: usize = 2048;
/// `MAX_EMAIL_CHARS`.
pub const MAX_EMAIL_CHARS: usize = 254;

/// `urlCheck`.
pub fn url_check(column: &str) -> String {
    format!("{column} IS NULL OR (char_length({column}) <= {MAX_URL_CHARS} AND {column} ~* '^(https?://[^[:space:]]+|mailto:[^[:space:]@]+@[^[:space:]]+)$')")
}

/// `emailCheck`.
pub fn email_check(column: &str) -> String {
    format!("{column} IS NULL OR (char_length({column}) <= {MAX_EMAIL_CHARS} AND {column} ~ '^[^[:space:]@]+@[^[:space:]@]+\\.[^[:space:]@]+$')")
}

/// `RICH_TEXT_FORBIDDEN_SQL`.
pub const RICH_TEXT_FORBIDDEN_SQL: [&str; 3] = [
    "<\\s*/?\\s*(script|iframe|object|embed|style|link|meta|svg|form|img|base|frame|frameset|applet|math)\\y",
    "\\son[a-z]+\\s*=",
    "javascript\\s*:",
];

/// `richTextCheck`.
pub fn rich_text_check(column: &str) -> String {
    let terms: Vec<String> = RICH_TEXT_FORBIDDEN_SQL.iter().map(|p| format!("{column} !~* '{p}'")).collect();
    format!("{column} IS NULL OR ({})", terms.join(" AND "))
}

/// `nullabilityOf`.
pub fn nullability_of(kind: &str, required: bool) -> &'static str {
    if kind == "autonumber" {
        return "";
    }
    if required && kind != "formula" {
        "NOT NULL"
    } else {
        "NULL"
    }
}

/// `pgTypeOf` for the kinds a table is created with (numbers at their default precision).
pub fn pg_type_of(kind: &str) -> R<&'static str> {
    Ok(match kind {
        "short_text" | "long_text" | "select" | "url" | "email" => "text",
        "autonumber" => "bigint GENERATED BY DEFAULT AS IDENTITY",
        "user" | "link" => "uuid",
        "number" => "numeric(38,10)",
        "multi_select" => "text[]",
        "file" | "image" => "jsonb",
        "boolean" => "boolean",
        "date" => "date",
        "datetime" => "timestamptz",
        "multi_link" => "uuid[]",
        "formula" => return Err(AppError::new("INTERNAL_ERROR").with("reason", json!("a formula type comes from its result")).with("kind", json!("formula"))),
        other => return Err(AppError::new("INTERNAL_ERROR").with("reason", json!("a field computed at read time has no column")).with("kind", json!(other))),
    })
}

/// `sqlCreateSchema`.
pub fn sql_create_schema(schema: &str) -> R<String> {
    Ok(format!("CREATE SCHEMA {};", quote_identifier(schema)?))
}

/// `SYSTEM_COLUMN_DEFINITIONS`.
const SYSTEM_COLUMN_DEFINITIONS: [&str; 5] = [
    "\"_id\"         uuid NOT NULL DEFAULT \"_basedb_local\".\"uuid_generate_v7\"()",
    "\"_created_at\" timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp()",
    "\"_updated_at\" timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp()",
    "\"_created_by\" uuid NULL",
    "\"_updated_by\" uuid NULL",
];

/// The five system columns (`SYSTEM_COLUMNS`).
pub const SYSTEM_COLUMNS: [&str; 5] = ["_id", "_created_at", "_updated_at", "_created_by", "_updated_by"];

/// `ColumnSpec`.
#[derive(Debug, Clone, PartialEq)]
pub struct ColumnSpec {
    pub name: String,
    pub kind: String,
    pub required: bool,
}

/// `sqlCreateTable`.
pub fn sql_create_table(schema: &str, table: &str, columns: &[ColumnSpec]) -> R<String> {
    for c in columns {
        if SYSTEM_COLUMNS.contains(&c.name.as_str()) {
            return Err(AppError::new("IDENTIFIER_INVALID").with("column", json!(c.name)).with("reason", json!("reserved system column")));
        }
    }
    let mut lines: Vec<String> = SYSTEM_COLUMN_DEFINITIONS.iter().map(|s| s.to_string()).collect();
    for c in columns {
        let quoted = quote_identifier(&c.name)?;
        let line = format!("{quoted:<13} {} {}", pg_type_of(&c.kind)?, nullability_of(&c.kind, c.required));
        lines.push(line.trim_end().to_string());
    }
    lines.push(format!("CONSTRAINT {} PRIMARY KEY (\"_id\")", quote_identifier(&primary_key_name(table))?));
    Ok(format!("CREATE TABLE {} (\n  {}\n);", qualify(schema, table)?, lines.join(",\n  ")))
}

/// `TRIGGER_ROLES`.
pub const TRIGGER_ROLES: [&str; 5] = ["system", "capture_ins", "capture_upd", "capture_del", "capture_trunc"];

/// `sqlTableTriggers`: the registry names and the five statements.
pub fn sql_table_triggers(schema: &str, table: &str, base_id: &str, table_id: &str) -> R<(Vec<String>, Vec<String>)> {
    let on = qualify(schema, table)?;
    let name = |role: &str| quote_identifier(&trigger_name(table, role));
    let capture = format!("_basedb_local.capture_v1({}, {}, '1')", quote_literal(base_id), quote_literal(table_id));
    let names = TRIGGER_ROLES.iter().map(|r| trigger_name(table, r)).collect();
    let statements = vec![
        format!("CREATE TRIGGER {} BEFORE INSERT OR UPDATE ON {on}\n  FOR EACH ROW EXECUTE FUNCTION _basedb_local.set_updated_at();", name("system")?),
        format!("CREATE TRIGGER {} AFTER INSERT ON {on}\n  REFERENCING NEW TABLE AS new_rows\n  FOR EACH STATEMENT EXECUTE FUNCTION {capture};", name("capture_ins")?),
        format!("CREATE TRIGGER {} AFTER UPDATE ON {on}\n  REFERENCING OLD TABLE AS old_rows NEW TABLE AS new_rows\n  FOR EACH STATEMENT EXECUTE FUNCTION {capture};", name("capture_upd")?),
        format!("CREATE TRIGGER {} AFTER DELETE ON {on}\n  REFERENCING OLD TABLE AS old_rows\n  FOR EACH STATEMENT EXECUTE FUNCTION {capture};", name("capture_del")?),
        format!("CREATE TRIGGER {} BEFORE TRUNCATE ON {on}\n  FOR EACH STATEMENT EXECUTE FUNCTION _basedb_local.assert_no_truncate();", name("capture_trunc")?),
    ];
    Ok((names, statements))
}

/// `sqlCommentOnTable`.
pub fn sql_comment_on_table(schema: &str, table: &str, label: &str) -> R<String> {
    Ok(format!("COMMENT ON TABLE {} IS {};", qualify(schema, table)?, quote_literal(label)))
}

/// `sqlCommentOnColumn`.
pub fn sql_comment_on_column(schema: &str, table: &str, column: &str, label: &str) -> R<String> {
    Ok(format!("COMMENT ON COLUMN {}.{} IS {};", qualify(schema, table)?, quote_identifier(column)?, quote_literal(label)))
}

async fn ddl<E: Exec + Sync>(exec: &E, sql: &str) -> R<()> {
    exec.execute_op(sql, &[], SqlOp::Ddl).await.map(|_| ())
}

/// `[...label].length`.
fn check_label_length(label: &str) -> R<()> {
    if label.chars().count() > MAX_LABEL_CHARS {
        return Err(AppError::new("LABEL_TOO_LONG").with("maximum", json!(MAX_LABEL_CHARS)));
    }
    Ok(())
}

fn look_refusal(reason: &str) -> AppError {
    AppError::new("REQUEST_INVALID").with("field", json!("look")).with("reason", json!(reason))
}


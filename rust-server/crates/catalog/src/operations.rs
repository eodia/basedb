/// `addPatternCheck`: the `CHECK` of a `url`, an `email` or a rich long text.
#[allow(clippy::too_many_arguments)]
pub async fn add_pattern_check<E: Exec + Sync>(exec: &E, ctx: &RequestContext, table_id: &str, base_id: &str, schema: &str, table: &str, field_id: &str, column: &str, rule: &str) -> R<Vec<String>> {
    let name = allocate_name(
        exec,
        ctx,
        &AllocationRequest::new(Candidate::Derived(check_constraint_name(table, column, rule)), ObjectKind::Constraint, ScopeKind::Table, table_id),
    )
    .await?;
    let constraint = exec
        .query_op(
            "INSERT INTO _basedb.table_constraint
               (table_id, base_id, kind, name_id, rule, origin, state, created_by)
             VALUES ($1::text::uuid, $2::text::uuid, 'check', $3::text::uuid, $4, 'system', 'active', $5::text::uuid) RETURNING id::text",
            &[&table_id, &base_id, &name.name_id, &rule, &ctx.actor.id],
            SqlOp::Insert,
        )
        .await?;
    let constraint_id: String = constraint.first().map(|r| r.get(0)).ok_or_else(|| AppError::internal("constraint not created"))?;
    exec.execute_op(
        "INSERT INTO _basedb.table_constraint_member (constraint_id, field_id, table_id, position)
         VALUES ($1::text::uuid, $2::text::uuid, $3::text::uuid, 1)",
        &[&constraint_id, &field_id, &table_id],
        SqlOp::Insert,
    )
    .await?;
    let quoted = quote_identifier(column)?;
    let body = match rule {
        "url" => url_check(&quoted),
        "email" => email_check(&quoted),
        _ => rich_text_check(&quoted),
    };
    let statement = format!("ALTER TABLE {} ADD CONSTRAINT {} CHECK ({body});", qualify(schema, table)?, quote_identifier(&name.name)?);
    ddl(exec, &statement).await?;
    Ok(vec![statement])
}

async fn insert_config_satellite<E: Exec + Sync>(exec: &E, field_id: &str, kind: &str) -> R<()> {
    let (sql, with_kind) = match kind {
        "short_text" | "long_text" => ("INSERT INTO _basedb.field_text_config (field_id, kind) VALUES ($1::text::uuid, $2)", true),
        "number" => ("INSERT INTO _basedb.field_number_config (field_id) VALUES ($1::text::uuid)", false),
        "boolean" => ("INSERT INTO _basedb.field_boolean_config (field_id) VALUES ($1::text::uuid)", false),
        "date" | "datetime" => ("INSERT INTO _basedb.field_datetime_config (field_id, kind) VALUES ($1::text::uuid, $2)", true),
        "url" | "email" | "autonumber" | "user" => return Ok(()),
        other => {
            return Err(AppError::new("FIELD_CONFIG_MISSING").with("kind", json!(other)).with("reason", json!("type outside the kernel vertical slice")));
        }
    };
    if with_kind {
        exec.execute_op(sql, &[&field_id, &kind], SqlOp::Insert).await?;
    } else {
        exec.execute_op(sql, &[&field_id], SqlOp::Insert).await?;
    }
    Ok(())
}


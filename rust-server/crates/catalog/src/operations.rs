/// `createTable` with `request.lineageId`: the table of another environment's lineage.
#[allow(clippy::too_many_arguments)]
pub async fn create_table_in_lineage(
    pools: &Pools,
    ctx: &RequestContext,
    base_id: &str,
    label: &str,
    description: Option<&Value>,
    fields: Option<&Value>,
    look: Option<&LookInput>,
    lineage: Option<&str>,
) -> R<CreatedTable> {
    let table_description = normalize_description(description, "description")?;
    let look: Look = match look {
        None => Look::default(),
        Some(l) => normalize_look(l, look_refusal)?,
    };
    let requests = field_requests(fields)?;
    let (table_description, look, requests) = (&table_description, &look, &requests);
    with_transaction(pools, PoolName::Ddl, ctx, TxOptions::default(), |tx| async move {
        require_on_base(&tx, ctx, Action::ManageSchema, base_id).await?;
        let schema = tx
            .first(
                "SELECT s.id::text, n.name
                   FROM _basedb.db_schema s
                   JOIN _basedb.physical_name n ON n.id = s.name_id
                  WHERE s.base_id = $1::text::uuid AND s.role = 'current' AND s.dropped_at IS NULL",
                &[&base_id],
            )
            .await?;
        let Some(schema) = schema else {
            return Err(AppError::new("RESOURCE_NOT_FOUND").with("base", json!(base_id)));
        };
        let (schema_id, schema_name): (String, String) = (schema.get(0), schema.get(1));
        let table_name = allocate_name(&tx, ctx, &AllocationRequest::new(Candidate::Label(label.to_string()), ObjectKind::Table, ScopeKind::Schema, schema_id.clone())).await?;
        let position = tx.first("SELECT COALESCE(MAX(position), 0) + 1 AS n FROM _basedb.table_def WHERE base_id = $1::text::uuid", &[&base_id]).await?;
        let position: i32 = position.map(|r| r.get(0)).unwrap_or(1);
        let table = tx
            .query_op(
                "INSERT INTO _basedb.table_def
                   (base_id, schema_id, name_id, label, label_key, description, position,
                    created_by, updated_by, lineage_id, color, icon, image)
                 VALUES ($1::text::uuid, $2::text::uuid, $3::text::uuid, $4, $5, $6, $7, $8::text::uuid, $8::text::uuid,
                         coalesce($9::text::uuid, _basedb_local.uuid_generate_v7()), $10, $11, $12) RETURNING id::text",
                &[&base_id, &schema_id, &table_name.name_id, &label, &label_key(label), table_description, &position, &ctx.actor.id, &lineage, &look.color, &look.icon, &look.image],
                SqlOp::Insert,
            )
            .await?;
        let table_id: String = table.first().map(|r| r.get(0)).ok_or_else(|| AppError::internal("table not created"))?;
        for column in SYSTEM_COLUMNS {
            tx.execute_op(
                "INSERT INTO _basedb.physical_name
                   (scope_kind, scope_id, name, object_kind, state, slug_version, allocated_by)
                 VALUES ('table', $1::text::uuid, $2, 'system_field', 'active', 1, $3::text::uuid)",
                &[&table_id, &column, &ctx.actor.id],
                SqlOp::Insert,
            )
            .await?;
        }

        let mut created: Vec<CreatedField> = Vec::new();
        let mut columns: Vec<ColumnSpec> = Vec::new();
        for f in requests.iter() {
            let candidate = candidate_of(f.label.as_ref(), f.technical_name.as_ref())?;
            let name = allocate_name(&tx, ctx, &AllocationRequest::new(candidate, ObjectKind::Field, ScopeKind::Table, table_id.clone())).await?;
            let Some(field_label) = f.label.as_ref().and_then(Value::as_str).map(str::to_string) else {
                return Err(AppError::internal("Cannot read properties of undefined (reading 'normalize')"));
            };
            let kind = f.kind.as_ref().and_then(Value::as_str).unwrap_or_default().to_string();
            let position = (created.len() + 1) as i32;
            let row = tx
                .query_op(
                    "INSERT INTO _basedb.field
                       (table_id, base_id, kind, name_id, label, label_key, description, is_required,
                        position, created_by, updated_by, lineage_id)
                     VALUES ($1::text::uuid, $2::text::uuid, $3, $4::text::uuid, $5, $6, $7, $8::text::boolean, $9, $10::text::uuid, $10::text::uuid,
                             coalesce($11::text::uuid, _basedb_local.uuid_generate_v7())) RETURNING id::text",
                    &[&table_id, &base_id, &kind, &name.name_id, &field_label, &label_key(&field_label), &f.description, &f.required_text, &position, &ctx.actor.id, &f.lineage_id],
                    SqlOp::Insert,
                )
                .await?;
            let field_id: String = row.first().map(|r| r.get(0)).ok_or_else(|| AppError::internal("field not created"))?;
            insert_config_satellite(&tx, &field_id, &kind).await?;
            columns.push(ColumnSpec { name: name.name.clone(), kind: kind.clone(), required: f.required_truthy });
            created.push(CreatedField { field_id, label: field_label, description: f.description.clone(), name: name.name, kind });
        }
        ddl(&tx, &sql_create_table(&schema_name, &table_name.name, &columns)?).await?;
        for f in created.iter().filter(|f| f.kind == "url" || f.kind == "email") {
            add_pattern_check(&tx, ctx, &table_id, base_id, &schema_name, &table_name.name, &f.field_id, &f.name, &f.kind).await?;
        }
        let (names, statements) = sql_table_triggers(&schema_name, &table_name.name, base_id, &table_id)?;
        for trigger in &names {
            tx.execute_op(
                "INSERT INTO _basedb.physical_name
                   (scope_kind, scope_id, name, object_kind, state, slug_version, allocated_by)
                 VALUES ('table', $1::text::uuid, $2, 'trigger', 'active', 1, $3::text::uuid)",
                &[&table_id, trigger, &ctx.actor.id],
                SqlOp::Insert,
            )
            .await?;
        }
        for s in &statements {
            ddl(&tx, s).await?;
        }
        tx.execute_op("INSERT INTO _basedb_local.change_feed_state (table_id, is_active) VALUES ($1::text::uuid, false)", &[&table_id], SqlOp::Insert).await?;
        ddl(&tx, &sql_comment_on_table(&schema_name, &table_name.name, comment_text(label, table_description.as_deref()))?).await?;
        for f in &created {
            ddl(&tx, &sql_comment_on_column(&schema_name, &table_name.name, &f.name, comment_text(&f.label, f.description.as_deref()))?).await?;
        }
        Ok(CreatedTable {
            table_id,
            description: table_description.clone(),
            qualified_name: qualify(&schema_name, &table_name.name)?,
            table_name: table_name.name,
            schema_name,
            fields: created,
        })
    })
    .await
}

struct TableLocation {
    base_id: String,
    label: String,
    description: Option<String>,
    table_name: String,
    schema_name: String,
}

async fn locate_table<E: Exec + Sync>(exec: &E, table_id: &str) -> R<TableLocation> {
    let row = exec
        .first(
            "SELECT t.base_id::text, t.label, t.description, tn.name AS table_name, sn.name AS schema_name
               FROM _basedb.table_def t
               JOIN _basedb.physical_name tn ON tn.id = t.name_id
               JOIN _basedb.db_schema s      ON s.id = t.schema_id
               JOIN _basedb.physical_name sn ON sn.id = s.name_id
              WHERE t.id = $1::text::uuid AND t.is_live",
            &[&table_id],
        )
        .await?;
    let Some(r) = row else {
        return Err(AppError::new("RESOURCE_NOT_FOUND").with("table", json!(table_id)));
    };
    Ok(TableLocation { base_id: r.get(0), label: r.get(1), description: r.get(2), table_name: r.get(3), schema_name: r.get(4) })
}

/// `updateTable`: label and look; `{label, color, icon, image}`.
pub async fn update_table(pools: &Pools, ctx: &RequestContext, table_id: &str, label: Option<&str>, look: Option<&LookInput>) -> R<Map<String, Value>> {
    let label = label.map(|l| crate::description::js_trim(l).to_string());
    if let Some(l) = &label {
        if l.is_empty() {
            return Err(AppError::new("LABEL_EMPTY").with("table", json!(table_id)));
        }
        check_label_length(l)?;
    }
    let look = match look {
        Some(l) if l.touches() => Some(normalize_look(l, look_refusal)?),
        _ => None,
    };
    let (label, look) = (&label, &look);
    with_transaction(pools, PoolName::Ddl, ctx, TxOptions::default(), |tx| async move {
        require_on_table(&tx, ctx, Action::ManageSchema, table_id).await?;
        let table = locate_table(&tx, table_id).await?;
        let grants = load_grants(&tx, ctx).await?;
        assert_manage_schema(&tx, ctx, &grants, &table.base_id).await?;
        let renames = label.as_deref().is_some_and(|l| l != table.label);
        if renames {
            let l = label.as_deref().unwrap_or_default();
            let clash = tx
                .rows(
                    "SELECT id::text FROM _basedb.table_def
                      WHERE base_id = $1::text::uuid AND label_key = $2 AND deleted_at IS NULL AND id <> $3::text::uuid",
                    &[&table.base_id, &label_key(l), &table_id],
                )
                .await?;
            if !clash.is_empty() {
                return Err(AppError::new("LABEL_DUPLICATE").with("label", json!(l)));
            }
        }
        let l = look.clone().unwrap_or_default();
        let key = label.as_deref().map(label_key);
        let rows = tx
            .query_op(
                "UPDATE _basedb.table_def
                    SET label = CASE WHEN $2::boolean THEN $3::text ELSE label END,
                        label_key = CASE WHEN $2::boolean THEN $4::text ELSE label_key END,
                        color = CASE WHEN $5::boolean THEN $6::text ELSE color END,
                        icon = CASE WHEN $5::boolean THEN $7::text ELSE icon END,
                        image = CASE WHEN $5::boolean THEN $8::text ELSE image END,
                        updated_at = clock_timestamp(), updated_by = $9::text::uuid
                  WHERE id = $1::text::uuid
                  RETURNING label, color, icon, image",
                &[&table_id, &renames, label, &key, &look.is_some(), &l.color, &l.icon, &l.image, &ctx.actor.id],
                SqlOp::Update,
            )
            .await?;
        let row = rows.first().ok_or_else(|| AppError::internal("Cannot read properties of undefined (reading 'label')"))?;
        let new_label: String = row.get(0);
        if renames {
            ddl(&tx, &sql_comment_on_table(&table.schema_name, &table.table_name, comment_text(&new_label, table.description.as_deref()))?).await?;
        }
        let mut out = Map::new();
        out.insert("label".into(), json!(new_label));
        out.insert("color".into(), json!(row.get::<_, Option<String>>(1)));
        out.insert("icon".into(), json!(row.get::<_, Option<String>>(2)));
        out.insert("image".into(), json!(row.get::<_, Option<String>>(3)));
        Ok(out)
    })
    .await
}


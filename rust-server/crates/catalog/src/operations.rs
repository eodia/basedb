/// The kinds a table can be created with (`CREATED_WITH_TABLE`).
pub const CREATED_WITH_TABLE: [&str; 10] = ["short_text", "long_text", "number", "boolean", "date", "datetime", "url", "email", "autonumber", "user"];

const COMPUTED_AT_CREATION: [&str; 5] = ["formula", "lookup", "rollup", "count", "button"];

/// One field of a `createTable` request, read from the body as Node passes it through.
#[derive(Debug, Clone, PartialEq)]
pub struct FieldRequest {
    pub label: Option<Value>,
    pub kind: Option<Value>,
    /// The JavaScript `required ?? false`, as PostgreSQL will read it, and its truthiness.
    pub required_text: String,
    pub required_truthy: bool,
    pub technical_name: Option<Value>,
    pub description: Option<String>,
    pub lineage_id: Option<String>,
}

/// JavaScript truthiness.
pub fn truthy(v: &Value) -> bool {
    match v {
        Value::Null => false,
        Value::Bool(b) => *b,
        Value::Number(n) => n.as_f64().is_some_and(|f| f != 0.0),
        Value::String(s) => !s.is_empty(),
        _ => true,
    }
}

/// How node-postgres sends a JavaScript value as a parameter.
fn pg_text(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

/// `request.fields` as `createTable` reads it — descriptions first, then the kinds.
pub fn field_requests(fields: Option<&Value>) -> R<Vec<FieldRequest>> {
    let items: Vec<Value> = match fields {
        None | Some(Value::Null) => Vec::new(),
        Some(Value::Array(a)) => a.clone(),
        Some(_) => return Err(AppError::internal("request.fields.map is not a function")),
    };
    let mut out = Vec::with_capacity(items.len());
    for (i, f) in items.iter().enumerate() {
        if f.is_null() {
            return Err(AppError::internal("Cannot read properties of null (reading 'description')"));
        }
        let get = |k: &str| f.as_object().and_then(|o| o.get(k)).cloned();
        let description = normalize_description(f.as_object().and_then(|o| o.get("description")), &format!("fields[{i}].description"))?;
        let required = get("required").filter(|v| !v.is_null()).unwrap_or(Value::Bool(false));
        out.push(FieldRequest {
            label: get("label"),
            kind: get("kind"),
            required_text: pg_text(&required),
            required_truthy: truthy(&required),
            technical_name: get("technicalName"),
            description,
            lineage_id: get("lineageId").filter(|v| !v.is_null()).map(|v| pg_text(&v)),
        });
    }
    let kind_in = |f: &FieldRequest, set: &[&str]| f.kind.as_ref().and_then(Value::as_str).is_some_and(|k| set.contains(&k));
    if let Some(i) = out.iter().position(|f| kind_in(f, &COMPUTED_AT_CREATION)) {
        return Err(AppError::new("REQUEST_INVALID").with("field", json!(format!("fields[{i}].kind"))).with("reason", json!("champ_calcule_apres_creation")));
    }
    if let Some(i) = out.iter().position(|f| !kind_in(f, &CREATED_WITH_TABLE)) {
        return Err(AppError::new("REQUEST_INVALID").with("field", json!(format!("fields[{i}].kind"))).with("reason", json!("champ_apres_creation")));
    }
    Ok(out)
}

fn candidate_of(label: Option<&Value>, technical: Option<&Value>) -> R<Candidate> {
    match (technical, label) {
        (Some(Value::String(t)), _) => Ok(Candidate::Technical(t.clone())),
        (Some(_), _) => Err(AppError::internal("technicalName is not a string")),
        (None, Some(Value::String(l))) => Ok(Candidate::Label(l.clone())),
        (None, None) => Err(AppError::new("INTERNAL_ERROR").with("reason", json!("allocation without label, technical name or derived name"))),
        (None, Some(_)) => Err(AppError::internal("label.normalize is not a function")),
    }
}


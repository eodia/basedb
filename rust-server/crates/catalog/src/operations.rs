/// `reorderFields`: every live field of the table, by physical name, in its new order.
pub async fn reorder_fields(pools: &Pools, ctx: &RequestContext, table_id: &str, names: &[String]) -> R<Vec<String>> {
    if names.is_empty() {
        return Err(AppError::new("REQUEST_INVALID").with("field", json!("fields")));
    }
    if let Some((_, repeated)) = names.iter().enumerate().find(|(i, n)| names.iter().position(|m| m == *n) != Some(*i)) {
        return Err(AppError::new("REQUEST_INVALID").with("field", json!("fields")).with("reason", json!("doublon")).with("detail", json!(repeated)));
    }
    with_transaction(pools, PoolName::Ddl, ctx, TxOptions::default(), |tx| async move {
        require_on_table(&tx, ctx, Action::ManageSchema, table_id).await?;
        let rows = tx
            .rows(
                "SELECT f.id::text, n.name, f.position
                   FROM _basedb.field f
                   JOIN _basedb.physical_name n ON n.id = f.name_id
                  WHERE f.table_id = $1::text::uuid AND f.is_live AND f.deleted_at IS NULL
                  ORDER BY f.position, f.created_at",
                &[&table_id],
            )
            .await?;
        let fields: Vec<(String, String, i32)> = rows.iter().map(|r| (r.get(0), r.get(1), r.get(2))).collect();
        if let Some(unknown) = names.iter().find(|n| !fields.iter().any(|f| &f.1 == *n)) {
            return Err(AppError::new("REQUEST_INVALID").with("field", json!("fields")).with("reason", json!("champ_inconnu")).with("detail", json!(unknown)));
        }
        let mut order: Vec<String> = names.to_vec();
        order.extend(fields.iter().filter(|f| !names.contains(&f.1)).map(|f| f.1.clone()));
        for (index, name) in order.iter().enumerate() {
            // Map semantics: the last row of a name wins.
            let Some(field) = fields.iter().rev().find(|f| &f.1 == name) else { continue };
            let position = (index + 1) as i32;
            if field.2 == position {
                continue;
            }
            tx.execute_op(
                "UPDATE _basedb.field SET position = $2, updated_at = clock_timestamp(), updated_by = $3::text::uuid WHERE id = $1::text::uuid",
                &[&field.0, &position, &ctx.actor.id],
                SqlOp::Update,
            )
            .await?;
        }
        Ok(order)
    })
    .await
}

